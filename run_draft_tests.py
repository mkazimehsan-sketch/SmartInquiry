"""Generate drafts for every test inquiry and check they are SAFE.

Usage: python run_draft_tests.py
Writes docs/draft_examples.md (all drafts) and prints a pass/fail safety report.

Automatic safety checks on every draft:
  1. No currency amounts or prices (no $, Rs, USD, PKR, 'per month', digits next to currency)
  2. No promises (refund approved, will be refunded, has shipped, will arrive on, guarantee ...)
  3. Starts with a greeting and ends with the sign-off
  4. Contains at least one [PLACEHOLDER] or a clarification question (so a human must act)
  5. An order ID appears only if the customer supplied it
  6. Fallback kinds are used for mixed / complaint / unclear / missing-ID inquiries
"""
import csv
import re
from pathlib import Path

from drafts import generate_draft
from classifier import ORDER_ID_PATTERN

ROOT = Path(__file__).parent
FILES = [ROOT / "data" / "sample_inquiries.csv", ROOT / "data" / "unseen_tests.csv"]

MONEY = re.compile(r"(\$|€|£|\brs\.?\b|\busd\b|\bpkr\b|\bper month\b|\bper year\b|\d+\s?%)", re.I)
PROMISES = re.compile(r"(refund (has been|is) approved|will be refunded|has (been )?shipped|"
                      r"will arrive (on|by|tomorrow)|we guarantee|replacement (is|has been) approved|"
                      r"free of charge)", re.I)

# Which kind of draft we expect for the tricky sample rows (id -> kind)
EXPECTED_KIND = {"6": "fallback_missing_order_id", "10": "fallback_unclear", "11": "fallback_unclear",
                 "12": "fallback_complaint", "13": "fallback_mixed", "14": "fallback_unclear",
                 "15": "fallback_mixed", "1": "pricing", "4": "order", "7": "support", "9": "support",
                 "104": "fallback_missing_order_id", "108": "fallback_complaint", "110": "fallback_mixed",
                 "112": "fallback_unclear"}


def check(row, d):
    problems = []
    if MONEY.search(d.text.replace("[PRICING DETAILS", "")):
        problems.append("contains a price/money amount")
    if PROMISES.search(d.text):
        problems.append("contains a promise")
    if not d.text.startswith("Hi "):
        problems.append("no greeting")
    if not d.text.rstrip().endswith("[BUSINESS NAME]"):
        problems.append("no sign-off")
    if not d.placeholders and "?" not in d.text:
        problems.append("no placeholder and no question")
    supplied = (row.get("order_id") or "").strip().upper()
    in_msg = ORDER_ID_PATTERN.search(row["message"])
    for oid in ORDER_ID_PATTERN.findall(d.text):
        if oid.upper() not in (supplied, (in_msg.group(0).upper() if in_msg else "")):
            problems.append(f"invented order id {oid}")
    exp = EXPECTED_KIND.get(row["id"])
    if exp and d.kind != exp:
        problems.append(f"expected kind {exp}, got {d.kind}")
    return problems


def main():
    out = ["# Draft examples (Day 3)", "",
           "Every draft below is generated by `drafts.py` and is meant to be **edited and approved by a person**.",
           "Text in `[CAPITAL BRACKETS]` is a placeholder the reviewer must fill in or delete. Nothing is auto-sent.", ""]
    total = bad = 0
    kinds = {}
    for f in FILES:
        for row in csv.DictReader(f.open(encoding="utf-8")):
            d = generate_draft(row["message"], row.get("order_id", ""), row["customer_name"])
            problems = check(row, d)
            total += 1
            kinds[d.kind] = kinds.get(d.kind, 0) + 1
            bad += bool(problems)
            out += [f"## #{row['id']} - {d.kind}" + ("  (FALLBACK)" if d.is_fallback else ""), "",
                    f"**Customer message:** {row['message'].strip() or '(blank)'}", "",
                    "```text", d.text, "```", "",
                    f"**Placeholders to fill:** {', '.join(d.placeholders) or 'none'}  ",
                    f"**Reviewer note:** {d.review_note}  ",
                    f"**Safety check:** {'FAIL - ' + '; '.join(problems) if problems else 'PASS'}", ""]
            if problems:
                print(f"FAIL #{row['id']}: {problems} | {row['message']}")
    summary = [f"- Drafts generated: **{total}**", f"- Safety checks passed: **{total - bad}/{total}**",
               "- Draft kinds: " + ", ".join(f"{k} = {v}" for k, v in sorted(kinds.items())), ""]
    out[4:4] = summary
    (ROOT / "docs" / "draft_examples.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{total - bad}/{total} drafts pass safety checks -> docs/draft_examples.md")
    print("kinds:", kinds)


if __name__ == "__main__":
    main()
